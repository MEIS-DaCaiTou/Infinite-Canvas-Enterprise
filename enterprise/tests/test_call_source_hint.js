const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
let resolveFetch;
let response;
const context={window:{},fetch:()=>response ? Promise.resolve({ok:true,json:async()=>response}) : new Promise(resolve=>{resolveFetch=resolve;}),Date,Symbol,URLSearchParams};
vm.runInNewContext(fs.readFileSync('static/js/generation-task-center.js','utf8'),context);
const hint=context.window.CallSourceHint;
const label={textContent:''};
(async()=>{
    const pending=hint.update(label,{id:'zhen',managed_source_supported:true});
    await hint.update(label,{id:'other',managed_source_supported:false});
    resolveFetch({ok:true,json:async()=>({state:'available',scope:'department',name:'设计部'})});
    await pending;
    assert.match(label.textContent,/未接通/,'late response must not overwrite the new provider');
    response={state:'available',scope:'department',name:'设计部'};
    await hint.update(label,{id:'zhen',managed_source_supported:true});
    assert.match(label.textContent,/部门专用 · 设计部/);
    assert.match(label.textContent,/实际以任务受理为准/);
    response={state:'not_authorized'};
    await hint.update(label,{id:'zhen',managed_source_supported:true});
    assert.match(label.textContent,/当前账号没有可用授权/);
    response={state:'legacy'};
    await hint.update(label,{id:'zhen',managed_source_supported:true});
    assert.match(label.textContent,/沿用原平台配置/);
    await hint.update(label,null);
    assert.match(label.textContent,/先选择可用平台/);
    console.log('Authorized source preview, provider change race and empty selection passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
