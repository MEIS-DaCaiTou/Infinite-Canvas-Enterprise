'use strict';
const fs=require('node:fs'), vm=require('node:vm'), path=require('node:path'), assert=require('node:assert/strict');
const ctx=vm.createContext({structuredClone});
vm.runInContext(fs.readFileSync(path.join(__dirname,'../../static/js/comfy-workflow-session.js'),'utf8'),ctx);
(async()=>{
    const session=new ctx.ComfyWorkflowSession([{id:'subject',default:'old.png'},{id:'mask'}]);
    let uploadDone;
    const upload=session.upload('subject',{},()=>new Promise(r=>uploadDone=r));
    let posts=0, submitted;
    await session.execute(()=>{posts++;},()=>{});
    assert.equal(posts,0,'uploading cannot submit the earlier image');
    assert.equal(session.values.subject,'');
    uploadDone({comfy_name:'input/actual.png'});await upload;
    assert.equal(session.values.subject,'input/actual.png');
    let completed;
    const run=session.execute(async values=>{posts++;submitted=values;return {task_id:'accepted'};},()=>new Promise(r=>completed=r));
    await new Promise(resolve=>setImmediate(resolve));
    await session.execute(()=>{posts++;},()=>{});
    session.set('subject','next.png');
    assert.equal(submitted.subject,'input/actual.png','running request snapshot is immutable');
    completed({status:'succeeded',result:{images:['/output/result.png'],videos:['/output/video.mp4']}});
    await run;
    assert.equal(posts,1,'two run controls share one guard');
    assert.notEqual(session.resultRevision,session.revision,'editing marks the earlier result stale');
    assert.equal(ctx.ComfyWorkflowResultItems(session.result).length,2);
    const failed=session.upload('subject',{},async()=>{throw new Error('offline');});
    await failed;
    assert.equal(session.values.subject,'','failed replacement cannot fall back to previous filename');
    assert.equal(session.error,'offline');
    await session.execute(async()=>({task_id:'original'}),async()=>{throw new Error('connection lost');});
    assert.equal(session.taskId,'original','lost query retains original accepted identity');
    console.log('shared inputs, upload failure, immutable run, one submission, typed results and original-task retention passed');
})().catch(error=>{console.error(error);process.exitCode=1;});
